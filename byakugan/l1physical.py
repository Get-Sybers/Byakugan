"""L1-physical — the artefact spindle-identity registry byakugan OWNS.

The physical half of Layer 1 (`L1-physical.db`): a SQLite registry whose schema
byakugan defines and both engines (godaemonhunter, gowindowlicker) and DX
consume. One row per artefact/asset holds the evidence *spindle* — host -> disk
-> volume -> image — captured at mount/collection time (the gomount manifest +
gohost / the SOFTWARE-hive MachineGuid), so a single, queryable thing names the
flat output (`<subtool>/<asset-id>.jsonl`) and stamps every record, superseding
the fragile per-lane host string that `docs/CAR-CrossSource.md` calls the master
blocker ("host identity fragmented across lanes") and `evidence-spine` FM-2
("cases collide"). The knowledge-registry brief and byakugan#136 scope it.

This module is the schema's source of truth and byakugan's own READ path:

* `render_ddl()` renders the DDL from the column definitions below — the single
  renderer. `python model/generate.py` writes it to the artifact the Go shared
  module embeds and this module reads, so the two consumers share one DDL and
  `verify_ddl()` fails on drift (the same discipline `byakugan.spindle --check`
  holds the spindle snapshot to).
* the reader (`connect`, `spindles`, `get`, `reconcile_hosts`) opens a per-case
  registry read-only and lets byakugan R2 reconcile host identity over the raw,
  as-is rows — reusing `byakugan.native_ids` for the canonicalisation it already
  owns (volume GUID, device/disk serial), never a second copy of those rules.

Stdlib only (sqlite3) — byakugan's runtime deps do not grow. The SQLite *write*
mechanics live in the Go shared module (go/l1physical), not here.

Decision 3 (byakugan ratifies): store the raw per-asset spindle + the OS-native
`host_id` (MachineGuid / machine-id / hw-UUID) AS-IS; byakugan R2 reconciles at
read time; no cross-OS unification in v1.

    python -m byakugan.l1physical [--out PATH] [--check]
"""
from __future__ import annotations

import argparse
import os
import re
import sqlite3
import sys

from . import native_ids

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)

# The DDL artifact lives UNDER the Go shared module so it can be go:embed'ed
# (embed cannot reach outside its module dir, and will not follow a symlink) —
# the same shape as go/internal/ir/ir.json, which Go embeds and Python reads.
# `python model/generate.py` writes it; this module reads it from the checkout.
DDL_PATH = os.path.join(_ROOT, "go", "l1physical", "schema.sql")

# The on-disk file name of a per-case registry: the logical db is
# "L1-physical.db", dot-prefixed so it stays outside byakugan's source-discovery
# walk (the .registry.db / _scratch lesson; decision 4).
DB_FILE_NAME = ".L1-physical.db"

# Forward-only schema version (decision 7); mirrored in PRAGMA user_version.
SCHEMA_VERSION = 1

TABLE = "spindle"

# The per-asset key columns = the flat-output leaf's precedence, in order.
KEY_COLUMNS = ("case_id", "asset_id")

# The spindle columns: (name, column-type/constraints, purpose). The order IS
# the CREATE TABLE order and the render is driven from here, so the DDL and the
# reader can never name a column the other does not.
COLUMNS: tuple[tuple[str, str, str], ...] = (
    ("case_id", "TEXT NOT NULL",
     "the asserted investigation scope (object-ids.yaml R2 case scope; "
     "CAR-CrossSource join A — scope is asserted, never inferred)"),
    ("asset_id", "TEXT NOT NULL",
     "the per-asset key = the flat-output leaf: first non-blank of "
     "disk_serial > volume_guid > image_sha256 > cleaned name"),
    ("host_id", "TEXT",
     "OS-native stable host id, stored AS-IS (Win MachineGuid / Linux "
     "machine-id / mac hw-UUID) — the master-blocker fix; R2 reconciles"),
    ("host_label", "TEXT",
     "the human host name (source_host / ComputerName), for R2 alias "
     "reconciliation of the fragmented per-lane strings; never the key"),
    ("disk_serial", "TEXT", "physical disk serial (gomount manifest)"),
    ("volume_guid", "TEXT", "volume GUID (gomount manifest)"),
    ("image_sha256", "TEXT", "evidence image SHA-256 (gomount manifest)"),
    ("name", "TEXT", "cleaned item-name fallback — the last rung of asset_id"),
    ("registered_at", "TEXT NOT NULL", "first registration time (UTC, ...Z)"),
    ("updated_at", "TEXT NOT NULL", "last upsert time (UTC, ...Z)"),
)

# The physical-identity fields a record is stamped with, beside its native
# values (fill-only) — exactly host.id + the gomount disk/volume/image (decision
# 7: the db takes ONLY the physical-identity role).
STAMP_FIELDS = ("host_id", "disk_serial", "volume_guid", "image_sha256")

_HEADER = f"""\
-- GENERATED by `python model/generate.py` (byakugan/l1physical.py:render_ddl)
--   — do not edit by hand.
--
-- L1-physical.db — the artefact spindle-identity registry byakugan OWNS
-- (knowledge-registry brief; byakugan#136). ONE SQLite file per case,
-- dot-prefixed ({DB_FILE_NAME}) and outside byakugan's source-discovery walk;
-- shared by both engines (godaemonhunter, gowindowlicker) and read by DX.
-- Embedded verbatim by the Go shared module (go/l1physical) and read by
-- byakugan's own Python (byakugan/l1physical.py) — the two consumers share
-- this one DDL.
--
-- One row per artefact/asset (the per-asset key = the flat leaf). It carries
-- the evidence spindle — host -> disk -> volume -> image — captured at mount/
-- collection time, stored AS-IS: byakugan R2 reconciles host identity
-- (object-ids.yaml R2 case scope; CAR-CrossSource), no cross-OS unification in
-- v1. Physical-identity role ONLY (decision 7); uid/gid/network enrichment
-- stays per-item JSONL.
"""


def render_ddl() -> str:
    """The L1-physical DDL as text — the single renderer. `model/generate.py`
    writes this to DDL_PATH; the Go module embeds it and this module reads it."""
    width = max(len(name) for name, _, _ in COLUMNS)
    lines = []
    for name, decl, _purpose in COLUMNS:
        lines.append(f"    {name.ljust(width)} {decl},")
    key = ", ".join(KEY_COLUMNS)
    lines.append(f"    PRIMARY KEY ({key})")
    body = "\n".join(lines)
    return (
        f"{_HEADER}\n"
        f"PRAGMA user_version = {SCHEMA_VERSION};\n\n"
        f"CREATE TABLE IF NOT EXISTS {TABLE} (\n{body}\n);\n\n"
        f"CREATE INDEX IF NOT EXISTS idx_{TABLE}_host\n"
        f"    ON {TABLE} (case_id, host_id);\n"
    )


def write_ddl(dest: str = DDL_PATH) -> str:
    """Render and write the DDL artifact. Returns the path written."""
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write(render_ddl())
    return dest


def load_ddl(path: str = DDL_PATH) -> str:
    """The committed DDL artifact, read from the checkout (byakugan reads the
    DDL directly, exactly as it reads go/internal/ir/ir.json)."""
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def verify_ddl(path: str = DDL_PATH) -> list[str]:
    """Drift guard: the committed DDL must equal render_ddl(). Returns a list of
    problems (empty == in sync), like byakugan.spindle.verify_*."""
    problems: list[str] = []
    if not os.path.exists(path):
        return [f"{path} is missing — run `python model/generate.py`"]
    if load_ddl(path) != render_ddl():
        problems.append(
            f"{path} is stale — run `python model/generate.py` "
            "(the committed DDL != byakugan.l1physical.render_ddl())")
    return problems


# --------------------------------------------------------------------------- #
# The per-asset key = the flat-output leaf.
# --------------------------------------------------------------------------- #
_UNSAFE = re.compile(r"[^A-Za-z0-9._-]+")


def _blank(value: object) -> bool:
    """byakugan's blank rule: None, "", whitespace and "-" are all blank."""
    if value is None:
        return True
    s = str(value).strip()
    return s == "" or s == "-"


def clean_name(name: object) -> str:
    """The cleaned item-name fallback rung: a filesystem-safe leaf. Conservative
    — basename, non-[A-Za-z0-9._-] collapsed to '_', stripped of leading/trailing
    separators; "" when nothing survives. Mirrors go/l1physical CleanName."""
    if _blank(name):
        return ""
    s = str(name).strip().replace("\\", "/")
    s = s.rsplit("/", 1)[-1]
    s = _UNSAFE.sub("_", s).strip("._-")
    return s


def asset_id(disk_serial: object = None, volume_guid: object = None,
             image_sha256: object = None, name: object = None) -> str:
    """The per-asset key: the first non-blank of disk_serial > volume_guid >
    image_sha256 > cleaned name (exactly the flat leaf). "" when none apply."""
    for value in (disk_serial, volume_guid, image_sha256):
        if not _blank(value):
            return str(value).strip()
    return clean_name(name)


# --------------------------------------------------------------------------- #
# The read path — byakugan R2 reconciles host identity over the as-is rows.
# --------------------------------------------------------------------------- #
def connect(db_path: str) -> sqlite3.Connection:
    """Open a per-case registry READ-ONLY (mode=ro — a read never creates or
    mutates the store, the .registry.db discipline). Rows come back as mappings."""
    if not os.path.exists(db_path):
        raise FileNotFoundError(db_path)
    uri = "file:" + os.path.abspath(db_path) + "?mode=ro"
    conn = sqlite3.connect(uri, uri=True)
    conn.row_factory = sqlite3.Row
    return conn


def spindles(conn: sqlite3.Connection, case_id: str | None = None) -> list[dict]:
    """Every spindle row (optionally scoped to one case), as dicts."""
    sql = f"SELECT * FROM {TABLE}"  # noqa: S608 — TABLE is a module constant
    params: tuple = ()
    if case_id is not None:
        sql += " WHERE case_id = ?"
        params = (case_id,)
    sql += " ORDER BY case_id, asset_id"
    return [dict(row) for row in conn.execute(sql, params)]


def get(conn: sqlite3.Connection, case_id: str, asset_id_: str) -> dict | None:
    """One spindle row by its per-asset key, or None."""
    row = conn.execute(
        f"SELECT * FROM {TABLE} WHERE case_id = ? AND asset_id = ?",  # noqa: S608
        (case_id, asset_id_)).fetchone()
    return dict(row) if row is not None else None


def reconcile_hosts(conn: sqlite3.Connection,
                    case_id: str | None = None) -> dict[str, dict]:
    """R2's host-identity reconciliation over the as-is rows: group assets by the
    stable OS-native `host_id` (the master-blocker fix — the key that is the same
    whoever parsed the image), collecting the fragmented human labels and the
    *canonical* volume GUIDs / disk serials byakugan.native_ids already defines.
    Keyed by host_id; rows with no host_id are grouped under "" (un-joinable —
    CAR-CrossSource: empty host is never fused). Canonicalisation happens HERE,
    at reconcile time, not at write time (decision 3: rows are stored as-is)."""
    hosts: dict[str, dict] = {}
    for row in spindles(conn, case_id):
        hid = (row.get("host_id") or "").strip()
        h = hosts.setdefault(hid, {
            "host_id": hid, "labels": set(), "assets": [],
            "volume_guids": set(), "disk_serials": set()})
        h["assets"].append(row["asset_id"])
        if not _blank(row.get("host_label")):
            h["labels"].add(str(row["host_label"]).strip())
        canon_vol = native_ids.canonical(row.get("volume_guid"))
        if canon_vol:
            h["volume_guids"].add(canon_vol)
        canon_serial = native_ids.as_serial(row.get("disk_serial"))
        if canon_serial:
            h["disk_serials"].add(canon_serial)
    return hosts


# --------------------------------------------------------------------------- #
# CLI — mirror byakugan.spindle: --check (drift gate) / --out (write).
# --------------------------------------------------------------------------- #
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="python -m byakugan.l1physical",
        description="Render / check the L1-physical registry DDL.")
    ap.add_argument("--out", metavar="PATH", default=None,
                    help=f"write the DDL (default {DDL_PATH})")
    ap.add_argument("--check", action="store_true",
                    help="fail if the committed DDL is stale")
    args = ap.parse_args(argv)
    if args.check:
        problems = verify_ddl()
        if problems:
            print("L1-physical DDL out of sync:\n  - " + "\n  - ".join(problems),
                  file=sys.stderr)
            return 1
        print("L1-physical DDL in sync")
        return 0
    dest = write_ddl(args.out or DDL_PATH)
    print(f"wrote {dest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
